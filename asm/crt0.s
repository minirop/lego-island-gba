.syntax unified
.arm

.global Init
Init:
	b crt0
	.include "asm/rom_header.inc"

.global crt0
crt0:
	mov r0, #0xd2
	msr cpsr_fc, r0
	ldr sp, IRQStackBottom
	mov r0, #0x1f
	msr cpsr_fc, r0
	ldr sp, unk_03007F00
	ldr r1, unk_03007FFC
	adr r0, GlobalIRQHandler
	str r0, [r1]
	ldr r1, AgbMain_ptr
	mov lr, pc
	bx r1
	b crt0
unk_03007F00:
	.4byte 0x03007F00
IRQStackBottom:
	.4byte 0x03007FA0

.byte 0x01, 0x00, 0x2d, 0xe9, 0x00, 0x00, 0x0f, 0xe1
.byte 0x80, 0x00, 0xc0, 0xe3, 0x00, 0xf0, 0x29, 0xe1
.byte 0x01, 0x00, 0xbd, 0xe8, 0x1e, 0xff, 0x2f, 0xe1
.byte 0x01, 0x00, 0x2d, 0xe9, 0x00, 0x00, 0x0f, 0xe1
.byte 0x80, 0x00, 0x80, 0xe3, 0x00, 0xf0, 0x29, 0xe1
.byte 0x01, 0x00, 0xbd, 0xe8, 0x1e, 0xff, 0x2f, 0xe1

unk_03007FFC:
	.4byte 0x03007FFC
AgbMain_ptr:
	.4byte 0x08000301

.global GlobalIRQHandler
